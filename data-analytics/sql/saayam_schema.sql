--
-- Saayam For All - schema for the request archival pipeline
--
-- The `requests` table and every table it references. Contains no data. This will be enough to help and understand the schema and to complete realted task ( 573) 
--


CREATE TABLE virginia_dev_saayam_rdbms.help_categories (
    cat_id           varchar(50)  PRIMARY KEY,
    cat_name         varchar(100) NOT NULL,
    cat_desc         varchar(150) NOT NULL,
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- Keys are hierarchy paths: '1', '1.3', '1.3.1'. 80 rows in dev.


CREATE TABLE virginia_dev_saayam_rdbms.help_categories_map (
    parent_id        varchar(50)  REFERENCES virginia_dev_saayam_rdbms.help_categories(cat_id),
    child_id         varchar(50)  PRIMARY KEY
                                  REFERENCES virginia_dev_saayam_rdbms.help_categories(cat_id),
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- The category tree, parent to child. NOT a join table for requests:
-- requests.req_cat_id joins straight to help_categories.cat_id.


CREATE TABLE virginia_dev_saayam_rdbms.request_for (
    req_for_id       serial       PRIMARY KEY,
    req_for          varchar(25)  NOT NULL,
    req_for_desc     varchar(125),
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- 0 = SELF, 1 = OTHER


CREATE TABLE virginia_dev_saayam_rdbms.request_isleadvol (
    req_islead_id    serial       PRIMARY KEY,
    req_islead       varchar(15)  NOT NULL,
    req_islead_desc  varchar(100),
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- 0 = NO, 1 = YES


CREATE TABLE virginia_dev_saayam_rdbms.request_types (
    req_type_id      serial       PRIMARY KEY,
    req_type         varchar(25),
    req_type_desc    varchar(125),
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- 0 = IN_PERSON, 1 = REMOTE


CREATE TABLE virginia_dev_saayam_rdbms.request_priorities (
    req_priority_id   serial       PRIMARY KEY,
    req_priority      varchar(25)  NOT NULL,
    req_priority_desc varchar(125),
    last_updated_at   timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- 0 = LOW, 1 = MEDIUM, 2 = HIGH, 3 = CRITICAL


CREATE TABLE virginia_dev_saayam_rdbms.request_statuses (
    req_status_id    serial       PRIMARY KEY,
    req_status       varchar(25)  NOT NULL,
    req_status_desc  varchar(125),
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- 0 CREATED, 1 MATCHING_VOLUNTEER, 2 IN_PROGRESS, 3 RESOLVED, 4 CANCELLED,
-- 5 DELETED, 6 RATED_BY_REQUESTER, 7 RATED_BY_VOLUNTEER, 8 VOLUNTEER_NOT_FOUND


-- ==================================================================== users

CREATE TABLE virginia_dev_saayam_rdbms.users (
    user_id          varchar(255) PRIMARY KEY,
    last_updated_at  timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- Key column only, see the header. IDs look like SID-00-000-000-000-000-026
-- and are generated by a trigger on insert, not by a sequence.


-- ================================================================= requests

CREATE TABLE virginia_dev_saayam_rdbms.requests (
    req_id             varchar(255) PRIMARY KEY,

    creator_id         varchar(255) NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.users(user_id),
    beneficiary_id     varchar(255)
                       REFERENCES virginia_dev_saayam_rdbms.users(user_id),
    lead_volunteer_id  varchar(255)
                       REFERENCES virginia_dev_saayam_rdbms.users(user_id),

    req_cat_id         varchar(50)  NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.help_categories(cat_id),
    req_for_id         integer      NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.request_for(req_for_id),
    req_islead_id      integer      NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.request_isleadvol(req_islead_id),
    req_type_id        integer      NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.request_types(req_type_id),
    req_priority_id    integer      NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.request_priorities(req_priority_id),
    req_status_id      integer      NOT NULL
                       REFERENCES virginia_dev_saayam_rdbms.request_statuses(req_status_id),

    req_subj           varchar(125) NOT NULL,
    req_desc           varchar(255) NOT NULL,
    req_doc_link       text,
    audio_req_desc     varchar(255),
    deletion_reason    text,

    req_loc            public.geometry(Point,4326),
    created_loc        public.geometry(Point,4326),

    iscalamity         boolean,
    to_public          boolean      DEFAULT false,

    submission_date    timestamp,
    serviced_date      timestamp,
    last_updated_at    timestamp(6) DEFAULT (now() AT TIME ZONE 'UTC')
);
-- req_id is generated by a trigger on insert, format REQ-000-000-000-0000.
-- last_updated_at drives the archival watermark.
-- Every timestamp here is `without time zone`. Values are UTC by convention,
-- nothing enforces it.


-- ========================================================== what joins what
--
-- The nine foreign keys above are the answer to "which columns reference 
-- other tables". Because they are enforced constraints, a non-null value is
-- guaranteed to match a row in its target. Null counts, from 221 requests in
-- dev on 24 October 2026:
--
--   lead_volunteer_id   218 null
--   beneficiary_id        8 null
--   everything else       0 null
--
-- An inner join on lead_volunteer_id would therefore return 3 rows of 221,
-- and the row count would look small rather than wrong.


